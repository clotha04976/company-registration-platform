export const taxBureauJurisdictions = BUREAUS;

export const purchaseProofTaxOffices = Object.freeze(OFFICE_ROWS.map(([bureauCode, county, officeName, districts, boundary = ""]) => Object.freeze({
  bureauCode: String(bureauCode),
  county: String(county),
  officeName: String(officeName),
  districts: Object.freeze(Array.isArray(districts) ? districts.map(String) : []),
  boundary: String(boundary),
})));

export function normalizeTaiwanAddress(value) {
  return String(value || "")
    .trim()
    .replace(/台/g, "臺")
    .replace(/巿/g, "市")
    .replace(/[\s　]+/g, "");
}

export function inferTaxBureau(address) {
  const normalizedAddress = normalizeTaiwanAddress(address);
  if (!normalizedAddress) return null;
  for (const item of BUREAUS) {
    const county = item.counties.find((candidate) => normalizedAddress.includes(candidate));
    if (county) return { bureauCode: item.code, bureauName: item.name, bureauShortName: item.shortName, county };
  }
  return null;
}

export function purchaseProofOfficeOptions(bureauNameOrCode = "") {
  const normalized = String(bureauNameOrCode || "").replace(/^臺北$/, "台北");
  const bureau = BUREAUS.find((item) => item.code === normalized || item.shortName === normalized || item.name === normalized);
  if (!bureau) return [];
  return [...new Set(purchaseProofTaxOffices.filter((item) => item.bureauCode === bureau.code).map((item) => item.officeName))];
}

export function inferTaxJurisdiction(address) {
  const bureau = inferTaxBureau(address);
  const normalizedAddress = normalizeTaiwanAddress(address);
  if (!bureau) return null;
  let candidates = purchaseProofTaxOffices.filter((item) => (
    item.bureauCode === bureau.bureauCode
    && item.county === bureau.county
    && item.districts.some((district) => normalizedAddress.includes(district))
  ));
  if (candidates.length > 1 && normalizedAddress.includes("中山區")) {
    if (normalizedAddress.includes("松江路以東")) candidates = candidates.filter((item) => item.boundary === "east");
    if (normalizedAddress.includes("松江路以西")) candidates = candidates.filter((item) => item.boundary === "west");
  }
  const branchCandidates = [...new Set(candidates.map((item) => item.officeName))];
  return {
    ...bureau,
    branchName: branchCandidates.length === 1 ? branchCandidates[0] : "",
    branchCandidates,
    needsBranchConfirmation: branchCandidates.length > 1,
  };
}
