/**
 * Trims the government business-item open data into the compact table the
 * wizard bundles.
 *
 * The published file carries ten columns per row and weighs 380 KB, most of it
 * statistics-bureau mappings and long legal descriptions the picker never
 * shows. Keeping only the code, the label and the category name brings it under
 * 40 KB, which is small enough to import directly instead of fetching at
 * runtime.
 *
 * Source: https://data.gcis.nat.gov.tw/od/data/api/FCB90AB1-E382-45CE-8D4F-394861851E28?$format=json&$top=5000
 *
 * The table is emitted as a module rather than JSON so that both Vite and the
 * plain Node test runner can import it without import attributes.
 *
 * Usage: node build/build-business-items.mjs [source.json] [output.mjs]
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = process.argv[2] ?? path.join(root, "BusinessScopeCategories.json");
const output = process.argv[3] ?? path.join(root, "lib", "business-items.mjs");

const rows = JSON.parse(readFileSync(source, "utf8"));
const categories = {};
const items = [];
const seen = new Set();
for (const row of rows) {
  const code = String(row.Business_Item ?? "").trim();
  const name = String(row.Business_Item_Desc ?? "").trim();
  if (!code || !name || seen.has(code)) continue;
  seen.add(code);
  const category = String(row.Category ?? "").trim();
  if (category) categories[category] = String(row.Category_Name ?? "").trim();
  items.push([code, name, category]);
}
items.sort((left, right) => left[0].localeCompare(right[0]));

const banner =
  "// Generated by build/build-business-items.mjs from the GCIS open data set.\n" +
  "// Do not edit by hand; rerun the script instead.\n";
writeFileSync(
  output,
  `${banner}export const categories = ${JSON.stringify(categories)};\n` +
    `export const items = ${JSON.stringify(items)};\n`,
  "utf8",
);
console.log(`${items.length} business items -> ${path.relative(root, output)}`);
